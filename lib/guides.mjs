export function guideBySlug(slug) {
  return GUIDES.find(g => g.slug === slug);
}

function guideTrail(g) {
  const t = [
    { name: '全国', href: paths.home(), abs: abs.home() },
    { name: 'ガイド', href: paths.guideIndex(), abs: abs.guideIndex() },
  ];
  if (g) t.push({ name: g.title, href: paths.guide(g.slug), abs: abs.guide(g.slug) });
  return t;
}

export function guidePage(g, dateModified) {
  const others = GUIDES.filter(x => x.slug !== g.slug);
  const body = `
<article class="prose">
  <h1>${esc(g.title)}</h1>
  ${g.body}
  ${section('ほかのガイド記事', '', `<ul class="guide-list">${others.map(o =>
    `<li><a href="${attr(paths.guide(o.slug))}">${esc(o.title)}</a><span class="note">${esc(o.description)}</span></li>`).join('')}</ul>`)}
  <p class="more"><a href="${attr(paths.guideIndex())}">ガイド記事の一覧へ</a></p>
</article>`;
  return page({
    title: `${g.title}${'｜'}${SITE.NAME}`,
    description: g.description,
    canonical: abs.guide(g.slug),
    trail: guideTrail(g),
    ogType: 'article',
    ld: [{
      '@context': 'https://schema.org',
      '@type': 'Article',
      headline: g.title,
      description: g.description,
      datePublished: dateModified,
      dateModified,
      publisher: {
        '@type': 'Organization', name: SITE.NAME, url: abs.home(),
        founder: { '@type': 'Person', name: SITE.OPERATOR_NAME },
      },
      mainEntityOfPage: abs.guide(g.slug),
    }],
  }, body);
}

