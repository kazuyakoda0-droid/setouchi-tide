// 干満差の大きさを全国の中で位置づける。しきい値は全国の観測点の
// 年平均干満差の分布（日本海側の20cm台から有明海の300cm近くまで）に合わせた。
function scaleWord(avg) {
  if (avg >= 220) return '全国でも最大級';
  if (avg >= 150) return '全国的に見て大きい部類';
  if (avg >= 90) return '全国のほぼ平均的な大きさ';
  if (avg >= 50) return '全国的には小さめ';
  return '全国でも最も小さい部類';
}

// 潮汐型。満潮が1日1回しか来ない日の割合から書き分ける。
function typeSentence(pct) {
  if (pct >= 30) {
    return `満潮が1日に1回しか来ない日が年間の${pct}%を占めます。潮が1日1往復しかしない<b>日周潮</b>の性質が強く出る海域で、「1日2回の満潮」を前提にした潮見表の読み方はそのままでは当てはまりません。`;
  }
  if (pct >= 15) {
    return `満潮が1日に1回しか来ない日が年間の${pct}%あります。1日2回の日と1回の日が月の周期で入れ替わるため、行く日によって潮の動き方の見え方が変わります。`;
  }
  return `ほとんどの日は満潮・干潮が1日2回ずつ訪れます（半日周潮）。満潮が1日1回だけの日は年間の${pct}%です。`;
}

// name: 「広島県」「中国地方」など。文中でそのまま使う。
export function profileText(name, note, pf, guideHref) {
  const ps = [];
  if (note) ps.push(`<p>${note}</p>`);

  ps.push(`<p>気象庁の推算値で${name}の観測点${pf.n}地点を通年で集計すると、1日の干満差は平均${pf.avg}cm、`
    + `大潮のころで${pf.spring}cm前後、小潮のころで${pf.neap}cm前後です。`
    + `これは${scaleWord(pf.avg)}にあたります。</p>`);

  ps.push(`<p>${typeSentence(pf.diurnalPct)}</p>`);

  const ratio = pf.min ? pf.max / pf.min : 1;
  const a = esc(pf.maxStation), b = esc(pf.minStation);
  if (ratio >= 2) {
    ps.push(`<p>同じ${name}の中でも地点差が大きく、年間で最も大きい干満差は${a}の${pf.max}cm、`
      + `最も小さい地点は${b}で${pf.min}cmです。面している海が違うと潮汐の大きさそのものが変わるため、`
      + `${name}の潮を見るときは<b>近い地点ではなく、同じ海に面した地点</b>を選ぶ必要があります。</p>`);
  } else if (ratio >= 1.3) {
    ps.push(`<p>年間で最も大きい干満差は${a}の${pf.max}cm、最も小さい地点は${b}の${pf.min}cmで、`
      + `${name}の中にもこれだけの幅があります。</p>`);
  } else {
    ps.push(`<p>年間で最も大きい干満差は${a}の${pf.max}cmで、${name}の中では地点による差はあまりありません。</p>`);
  }

  if (guideHref) {
    ps.push(`<p>干満差が地域によってここまで違う理由は<a href="${guideHref}">干満差は地域でこんなに違う</a>で説明しています。</p>`);
  }
  return ps.join('\n');
}
